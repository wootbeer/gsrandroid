int gsr_text_cell_w(int scale) { return 6 * scale; }
int gsr_text_cell_h(int scale) { return 9 * scale; }

static const unsigned char *glyph_rows(char c) {
	static const unsigned char blank[7] = {0};
	c = (char)toupper((unsigned char)c);
	for (unsigned i = 0; i < sizeof k_glyphs / sizeof k_glyphs[0]; i++)
		if (k_glyphs[i].c == c) return k_glyphs[i].row;
	return blank;
}

void gsr_text_draw(int surface_h, int x, int y, int scale, const char *s, float r, float g, float b) {
	glEnable(GL_SCISSOR_TEST);
	glClearColor(r, g, b, 1.0f);
	for (; *s; s++, x += 6 * scale) {
		const unsigned char *rows = glyph_rows(*s);
		for (int ry = 0; ry < 7; ry++) {
			int bx = 0;
			while (bx < 5) {
				if (!(rows[ry] & (0x10 >> bx))) { bx++; continue; }
				int run = 1;
				while (bx + run < 5 && (rows[ry] & (0x10 >> (bx + run)))) run++;
				glScissor(x + bx * scale, surface_h - (y + (ry + 1) * scale), run * scale, scale);
				glClear(GL_COLOR_BUFFER_BIT);
				bx += run;
			}
		}
	}
	glDisable(GL_SCISSOR_TEST);
}

int gsr_text_paragraph(int surface_h, int x, int y, int scale, int max_chars, const char *s, float r, float g, float b) {
	char line[160];
	int lines = 0;
	if (max_chars > (int)sizeof line - 1) max_chars = (int)sizeof line - 1;
	if (max_chars < 4) max_chars = 4;
	while (*s) {
		while (*s == ' ') s++;
		if (!*s) break;
		size_t len = strlen(s), take = len < (size_t)max_chars ? len : (size_t)max_chars;
		const char *nl = memchr(s, '\n', take);
		if (nl) take = (size_t)(nl - s);
		else if (take < len) { /* break at the last space if there is one */
			size_t k = take;
			while (k > 0 && s[k] != ' ') k--;
			if (k > 0) take = k;
		}
		memcpy(line, s, take);
		line[take] = 0;
		gsr_text_draw(surface_h, x, y + lines * gsr_text_cell_h(scale), scale, line, r, g, b);
		lines++;
		s += take;
		if (*s == '\n') s++;
	}
	return lines;
}

void gsr_text_blit(const char *s, int scale, unsigned char *dst, int stride, int x, int y) {
	for (; *s; s++, x += 6 * scale) {
		const unsigned char *rows = glyph_rows(*s);
		for (int ry = 0; ry < 7; ry++)
			for (int bx = 0; bx < 5; bx++)
				if (rows[ry] & (0x10 >> bx))
					for (int py = 0; py < scale; py++)
						memset(dst + (size_t) (y + ry * scale + py) * stride + x + bx * scale, 255, (size_t) scale);
	}
}
